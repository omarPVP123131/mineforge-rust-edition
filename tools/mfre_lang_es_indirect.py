def holes(s: str) -> list[str]:
    return sorted(re.findall(r"\{(\w+)\}", s))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--report", action="store_true")
    ap.parse_args()
    table = json.loads(ES.read_text())
    for en, said in TRANSLATIONS.items():
        assert holes(en) == holes(said), en
        assert said.strip(), en
    missing = [k for k in TRANSLATIONS if k not in table]
    present = [k for k in TRANSLATIONS if k in table]
    print(f"es.json: {len(table)} keys; TRANSLATIONS holds {len(TRANSLATIONS)}; "
          f"absent from the catalog: {len(missing)}; already present: {len(present)}")
    for k in missing[:10]:
        print(f"  absent: {k!r}")
    if not missing:
        return 0
    if not any(a == "--apply" for a in sys.argv[1:]):
        return 0
    table.update(TRANSLATIONS)
    ES.write_text(json.dumps(table, ensure_ascii=False, indent=2) + "\n")
    print(f"wrote es.json with {len(table)} keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
