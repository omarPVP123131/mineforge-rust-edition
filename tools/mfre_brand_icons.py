#!/usr/bin/env python3
"""MFRE (Fase 10): the fork's own brand masters and every rendered icon.

Single source of truth for the MineForge mark: an M whose middle stroke is a
forge spark, drawn on whole units of the same 16-unit grid upstream used. This
script writes the SVG masters in docs/media/brand AND rasterises every output
`cargo run -p xtask -- icons` would write, so the fork's icons can be rebuilt
without librsvg (rsvg-convert). On hardware that has rsvg-convert, xtask icons
renders the same masters; the geometry lives here and in the masters only.

Zero Mojang assets (TRAYECTORIA aviso de marca, mitigación 2): everything is
rectangles generated by this script.

Usage: python3 tools/mfre_brand_icons.py   (from the repo root)
"""
import os
import struct
import sys

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The mark on the 16-unit grid: (x, y, w, h). A five-column pixel M — outer
# stems full height, the diagonals stepping in one row down — whose middle
# vertex hangs a row lower in the accent: the forge spark.
STEMS = [(3, 2, 2, 12), (11, 2, 2, 12), (5, 4, 2, 2), (9, 4, 2, 2)]
SPARK = (7, 6, 2, 3)

BG = "#16181f"      # the tile, as dark as upstream's
INK = "#ecedf3"     # the mark on the tile
INK_LIGHT = "#16181f"  # the mark alone, for light backgrounds
SPARK_DARK_BG = "#f97316"  # molten orange on dark
SPARK_LIGHT_BG = "#d35400"  # and readable on light

HICOLOR = [16, 24, 32, 48, 64, 128, 256, 512]
ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
ICNS = [
    (b"icp4", 16), (b"icp5", 32), (b"icp6", 64), (b"ic07", 128),
    (b"ic08", 256), (b"ic09", 512), (b"ic10", 1024), (b"ic11", 32),
    (b"ic12", 64), (b"ic13", 256), (b"ic14", 512),
]


def rects(stem_fill, spark_fill, opacity_stems=1.0):
    out = [f'<g fill="{stem_fill}"'
           + (f' opacity="{opacity_stems}"' if opacity_stems != 1.0 else "")
           + ">"]
    out += [f'<rect x="{x}" y="{y}" width="{w}" height="{h}"/>' for x, y, w, h in STEMS]
    out.append("</g>")
    out.append(f'<rect x="{SPARK[0]}" y="{SPARK[1]}" width="{SPARK[2]}" height="{SPARK[3]}" fill="{spark_fill}"/>')
    return "".join(out)


def write(path, text):
    full = os.path.join(REPO, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", path)


def masters():
    """The SVG masters (docs/media/brand)."""
    write("docs/media/brand/icon.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">
  <title>MineForge Rust Edition</title>
  <clipPath id="tile"><rect width="16" height="16" rx="3.5"/></clipPath>
  <g clip-path="url(#tile)">
    <rect width="16" height="16" fill="{BG}"/>
    {rects(INK, SPARK_DARK_BG)}
  </g>
</svg>
''')
    write("docs/media/brand/icon-macos.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <title>MineForge Rust Edition</title>
  <clipPath id="tile"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath>
  <g clip-path="url(#tile)">
    <rect x="100" y="100" width="824" height="824" fill="{BG}"/>
    <g transform="translate(100 100) scale(51.5)">
      {rects(INK, SPARK_DARK_BG)}
    </g>
  </g>
</svg>
''')
    write("docs/media/brand/avatar.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">
  <title>MineForge Rust Edition</title>
  <rect width="16" height="16" fill="{BG}"/>
  <g transform="translate(2.4 2.4) scale(.7)">
    {rects(INK, SPARK_DARK_BG)}
  </g>
</svg>
''')
    write("docs/media/brand/mark.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">
  <title>MineForge Rust Edition</title>
  {rects(INK_LIGHT, SPARK_LIGHT_BG)}
</svg>
''')
    write("docs/media/brand/mark-dark.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">
  <title>MineForge Rust Edition</title>
  {rects(INK, SPARK_DARK_BG)}
</svg>
''')
    write("docs/media/brand/web/favicon.svg", open(os.path.join(REPO, "docs/media/brand/icon.svg"), encoding="utf-8").read())


def render(size, tile=None, margin=0.0, rx=None, scale=1.0, offset=(0.0, 0.0)):
    """The mark (and its tile) as a PNG of `size` px, 8x supersampled.

    `tile`: background colour of the rounded square, or None for no tile.
    `margin`: fraction of the canvas left empty on each side (Apple's grid).
    `rx`: corner radius in 16-grid units (3.5 upstream), scaled with the tile.
    """
    ss = 8
    px = size * ss
    img = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    from PIL import ImageDraw
    d = ImageDraw.Draw(img)

    # The 16-grid content area inside the canvas.
    content = px * (1 - 2 * margin)
    ox, oy = px * margin, px * margin
    unit = content / 16.0

    if tile is not None:
        r = (rx / 16.0) * content if rx else 0
        d.rounded_rectangle([ox, oy, ox + content, oy + content], radius=r, fill=tile)

    # Content transform (avatar shrinks the mark; offset/scale from the masters).
    cu = unit * scale
    cox = ox + offset[0] * unit
    coy = oy + offset[1] * unit

    def box(x, y, w, h):
        return [cox + x * cu, coy + y * cu, cox + (x + w) * cu, coy + (y + h) * cu]

    for x, y, w, h in STEMS:
        d.rectangle(box(x, y, w, h), fill=INK)
    d.rectangle(box(*SPARK), fill=SPARK_DARK_BG)

    return img.resize((size, size), Image.LANCZOS)


def hexrgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def png(img):
    import io
    b = io.BytesIO()
    img.save(b, "PNG")
    return b.getvalue()


def save(img, path):
    full = os.path.join(REPO, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    img.save(full, "PNG")
    print("wrote", path)


def square(size):
    return render(size, tile=hexrgb(BG), rx=3.5)


def macos(size):
    # Apple's grid: 824/1024 tile, 185/824 corners → margin 100/1024, rx 185/824 of the tile.
    return render(size, tile=hexrgb(BG), margin=100 / 1024, rx=185 / 51.5)


def avatar(size):
    return render(size, tile=hexrgb(BG), scale=0.7, offset=(2.4, 2.4))


def ico(images):
    """A Windows .ico: ICONDIR + PNG-compressed entries (Vista and later)."""
    out = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    for size, data in images:
        w = 0 if size >= 256 else size
        out += struct.pack("<BBBBHHII", w, w, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    for _, data in images:
        out += data
    return out


def icns(entries):
    """An Apple .icns: 'icns' + total size, then (ostype, size, PNG) entries."""
    body = b"".join(
        kind + struct.pack(">I", 8 + len(data)) + data for kind, data in entries
    )
    return b"icns" + struct.pack(">I", 8 + len(body)) + body


def main():
    masters()
    # Linux hicolor tree, and the scalable copy of the master.
    for s in HICOLOR:
        save(square(s), f"packaging/icons/hicolor/{s}x{s}/apps/horizon.png")
    # Windows .ico (embedded in the binaries by their build.rs).
    images = [(s, png(square(s))) for s in ICO_SIZES]
    os.makedirs(os.path.join(REPO, "packaging/icons"), exist_ok=True)
    with open(os.path.join(REPO, "packaging/icons/horizon.ico"), "wb") as f:
        f.write(ico(images))
    print("wrote packaging/icons/horizon.ico")
    # macOS .icns, on Apple's grid.
    entries = [(kind, png(macos(s))) for kind, s in ICNS]
    with open(os.path.join(REPO, "packaging/icons/horizon.icns"), "wb") as f:
        f.write(icns(entries))
    print("wrote packaging/icons/horizon.icns")
    # The game window's icon at run time.
    save(square(64), "crates/horizon-theme/icons/horizon-64.png")
    # Avatars, previews and the website's icons.
    save(avatar(500), "docs/media/brand/social/github-avatar-500.png")
    save(avatar(180), "docs/media/brand/web/apple-touch-icon.png")
    save(square(32), "docs/media/brand/web/favicon-32.png")
    save(square(1024), "docs/media/brand/icon-1024.png")
    save(macos(1024), "docs/media/brand/icon-macos-1024.png")
    print("done: MFRE brand masters and icons")


if __name__ == "__main__":
    sys.exit(main())
